"""
IBM Quantum hardware execution script for the QClearance pipeline.

This script loads the pre-converged variational circuits generated by
`02_quantum_stiff_dynamics.py` and `03_quantum_polypharmacy_qaoa.py`, compiles
them to the target processor's Heavy-Hex instruction set architecture (ISA) via
`generate_preset_pass_manager(optimization_level=3)`, constructs post-transpile
barrier-protected 3x native 2Q-folded circuits and live 8-qubit readout
calibration circuits on the exact same physical qubits, and submits the 8-PUB
batch through Qiskit IBM Runtime V2 (`SamplerV2`) with native XX dynamical
decoupling and Pauli gate/measurement twirling.

Submitted hardware workload (~20-30 seconds of QPU time on Heron r2):
  0-1. 8-qubit all-|0> and all-|1> readout calibration on the VQLS physical qubits
  2-3. 8-qubit Osimertinib Brickwall VQLS ansatz (1x baseline + 3x native CZ-folded ZNE)
  4-5. 10-qubit core cardio-oncology polypharmacy HH-CD-QAOA (1x + 3x native CZ-folded ZNE)
  6.   50-qubit multi-slot Heavy-Hex HH-CD-QAOA scaling circuit (p = 2)
  7.   100-qubit utility-scale Heavy-Hex HH-CD-QAOA circuit (p = 2)

Outputs written to `results/04_ibm_hardware/`:
  - ibm_job_manifest.json (backend name, job ID, physical qubits, transpiled depths, and 2Q counts)
  - ibm_raw_hardware_counts.json (untouched raw hardware bitstring counts per PUB)
  - ibm_hardware_vqlds_trajectories.csv (72-h Osimertinib/AZ5104/AZ7550 raw, RO, and ZNE curves)
  - ibm_real_hardware_results.json (decoded Osimertinib PK & 10-100q QAOA hardware metrics)
"""

