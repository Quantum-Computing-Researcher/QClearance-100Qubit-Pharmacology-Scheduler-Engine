def build_8q_vqlds_circuit(gate_list: list, n_qubits: int = 8, cx_fold: int = 1) -> QuantumCircuit:
    """Rebuild the 8-qubit nearest-neighbor Brickwall VQLS circuit from serialized instructions."""
    qc = QuantumCircuit(n_qubits, name=f"vqlds_8q_fold{cx_fold}")
    for item in gate_list:
        gname = item["gate"]
        qargs = item["qubits"]
        pars = item["params"]
        if gname == "ry":
            qc.ry(pars[0], qargs[0])
        elif gname == "rx":
            qc.rx(pars[0], qargs[0])
        elif gname == "rz":
            qc.rz(pars[0], qargs[0])
        elif gname == "u":
            qc.u(pars[0], pars[1], pars[2], qargs[0])
        elif gname == "cx":
            for _ in range(cx_fold):
                qc.cx(qargs[0], qargs[1])
    qc.measure_all()
    return qc


def build_heavy_hex_edges(n_qubits: int) -> list:
    """Construct degree-<=3 Heavy-Hex graph edges matching `03_quantum_polypharmacy_qaoa.py`."""
    edges = [(q, q + 1) for q in range(n_qubits - 1)]
    if n_qubits == 10:
        return edges + [(0, 5), (2, 7)]

    used_deg3 = set()
    for u in range(0, n_qubits - 6, 4):
        v = u + 5
        if u not in used_deg3 and v not in used_deg3:
            edges.append((u, v))
            used_deg3.add(u)
            used_deg3.add(v)
    return edges


def compute_cd_gauge_weights(h_vec: np.ndarray, j_weights: dict, n_qubits: int) -> np.ndarray:
    """Compute local cavity adiabatic gauge weights g_i matching `03_quantum_polypharmacy_qaoa.py`."""
    neighbors = [[] for _ in range(n_qubits)]
    for (u, v), w_uv in j_weights.items():
        neighbors[u].append((v, w_uv))
        neighbors[v].append((u, w_uv))

    m_cav = np.tanh(-0.8 * h_vec)
    for _ in range(4):
        m_next = np.zeros(n_qubits, dtype=float)
        for u in range(n_qubits):
            eff_field = h_vec[u] + sum(w_uv * m_cav[v] for (v, w_uv) in neighbors[u])
            m_next[u] = np.tanh(-0.85 * eff_field)
        m_cav = 0.5 * m_cav + 0.5 * m_next

    g_1q = np.zeros(n_qubits, dtype=float)
    for u in range(n_qubits):
        h_eff = h_vec[u] + sum(w_uv * m_cav[v] for (v, w_uv) in neighbors[u])
        denom = h_eff ** 2 + sum(w_uv ** 2 for (_, w_uv) in neighbors[u]) + 0.35
        g_1q[u] = h_eff / denom
    return g_1q


def estimate_sparse_energy_bounds(h_vec: np.ndarray, j_dense: np.ndarray, n_qubits: int) -> tuple:
    """
    Compute exact Ising spectrum bounds for N <= 12 or multi-start simulated annealing
    bounds for N = 50, 100 matching `03_quantum_polypharmacy_qaoa.py`.
    """
    if n_qubits <= 12:
        dim = 1 << n_qubits
        idx = np.arange(dim)
        spins = np.zeros((dim, n_qubits), dtype=float)
        for q in range(n_qubits):
            spins[:, q] = np.where(((idx >> q) & 1) == 0, 1.0, -1.0)
        energies = spins @ h_vec
        for i in range(n_qubits):
            for j in range(i + 1, n_qubits):
                if abs(j_dense[i, j]) > 1e-12:
                    energies += j_dense[i, j] * spins[:, i] * spins[:, j]
        return float(np.min(energies)), float(np.max(energies))

    rng = np.random.default_rng(777 + n_qubits)
    best_min = 1e9
    best_max = -1e9
    temps = np.geomspace(2.5, 0.04, 45)
    for _ in range(48):
        s_min = rng.choice([-1.0, 1.0], size=n_qubits)
        s_max = s_min.copy()
        for temp in temps:
            for q in range(n_qubits):
                field_min = h_vec[q] + float(np.dot(j_dense[q], s_min))
                d_e_min = -2.0 * s_min[q] * field_min
                if d_e_min < 0.0 or rng.random() < np.exp(-d_e_min / temp):
                    s_min[q] = -s_min[q]

                field_max = h_vec[q] + float(np.dot(j_dense[q], s_max))
                d_e_max = -2.0 * s_max[q] * field_max
                if d_e_max > 0.0 or rng.random() < np.exp(d_e_max / temp):
                    s_max[q] = -s_max[q]

        e_lo = float(np.dot(h_vec, s_min) + 0.5 * (s_min @ j_dense @ s_min))
        e_hi = float(np.dot(h_vec, s_max) + 0.5 * (s_max @ j_dense @ s_max))
        best_min = min(best_min, e_lo)
        best_max = max(best_max, e_hi)

    return best_min, best_max


def build_nq_hh_cd_qaoa_circuit(n_qubits: int, df_poly: pd.DataFrame, qaoa_params: dict) -> tuple:
    """
    Rebuild the N-qubit Heavy-Hex Counterdiabatic QAOA circuit (N = 10, 50, or 100)
    by tiling the exact ChEMBL 10-drug cohort couplings identically to `03_quantum_polypharmacy_qaoa.py`.
    """
    edges = build_heavy_hex_edges(n_qubits)
    conc = df_poly["therapeutic_conc_uM"].to_numpy(dtype=float)
    ki = df_poly["extracted_potency_uM"].to_numpy(dtype=float)
    base_ddi = df_poly["hepatic_ddi_ratio_I_over_Ki"].to_numpy(dtype=float)

    h_vec_10 = np.zeros(10, dtype=float)
    h_vec_10[0] = -1.60
    for i in range(1, 10):
        h_vec_10[i] = -0.12 * np.log1p(base_ddi[i])

    j_dense_10 = np.zeros((10, 10), dtype=float)
    for i in range(10):
        for j in range(i + 1, 10):
            mutual = (conc[i] / max(ki[j], 0.02)) + (conc[j] / max(ki[i], 0.02))
            j_dense_10[i, j] = round(float(0.38 * np.log1p(mutual)), 5)
            j_dense_10[j, i] = j_dense_10[i, j]

    h_vec = np.array([float(h_vec_10[i % 10]) for i in range(n_qubits)], dtype=float)
    j_weights = {}
    j_dense = np.zeros((n_qubits, n_qubits), dtype=float)
    for (u, v) in edges:
        w = round(float(j_dense_10[u % 10, v % 10]), 5)
        j_weights[(u, v)] = w
        j_dense[u, v] = w
        j_dense[v, u] = w

    # Direct parameter transfer without ad-hoc rescaling
    gammas = np.array(qaoa_params["gammas"], dtype=float)
    betas = np.array(qaoa_params["betas"], dtype=float)
    alphas = np.array(qaoa_params["alphas"], dtype=float)
    g_1q = compute_cd_gauge_weights(h_vec, j_weights, n_qubits)

    qc = QuantumCircuit(n_qubits, name=f"hh_cd_qaoa_{n_qubits}q")
    qc.h(range(n_qubits))
    for layer in range(len(gammas)):
        gam, bet, alp = float(gammas[layer]), float(betas[layer]), float(alphas[layer])
        for q in range(n_qubits):
            if abs(h_vec[q]) > 1e-12:
                qc.rz(2.0 * gam * float(h_vec[q]), q)
        for (u, v) in edges:
            angle = 2.0 * gam * j_weights[(u, v)]
            qc.cx(u, v)
            qc.rz(angle, v)
            qc.cx(u, v)
        for q in range(n_qubits):
            qc.rx(2.0 * bet, q)
            if abs(g_1q[q]) > 1e-12:
                qc.ry(2.0 * alp * float(g_1q[q]), q)
    qc.measure_all()
    return qc, h_vec, j_weights, j_dense


def fold_isa_2q_gates(isa_qc: QuantumCircuit, fold_factor: int = 3, name: str = None) -> QuantumCircuit:
    """
    Odd-fold native two-qubit ISA gates (`cz`, `ecr`, `cx`) AFTER `optimization_level=3`
    transpilation, separating folded copies with barriers so neither Qiskit nor runtime
    compilation cancels them, while preserving the exact same physical qubits as `isa_qc`.
    """
    folded = QuantumCircuit(*isa_qc.qregs, *isa_qc.cregs, name=name or f"{isa_qc.name}_fold{fold_factor}")
    for inst in isa_qc.data:
        if inst.operation.name in ("cz", "ecr", "cx") and fold_factor > 1:
            for k in range(fold_factor):
                if k > 0:
                    folded.barrier(*inst.qubits)
                folded.append(inst.operation, inst.qubits, inst.clbits)
        else:
            folded.append(inst.operation, inst.qubits, inst.clbits)
    return folded


def build_isa_readout_cal_circuits(isa_8q: QuantumCircuit, backend_op_names: set) -> tuple:
    """
    Construct all-|0> and all-|1> readout calibration ISA circuits on the exact 8 physical
    qubits measured in `isa_8q` to measure live hardware assignment errors in the same batch.
    """
    meas_insts = [inst for inst in isa_8q.data if inst.operation.name == "measure"]
    ro0 = QuantumCircuit(*isa_8q.qregs, *isa_8q.cregs, name="vqlds_8q_ro0")
    ro1 = QuantumCircuit(*isa_8q.qregs, *isa_8q.cregs, name="vqlds_8q_ro1")

    meas_qubits = [inst.qubits[0] for inst in meas_insts]
    if "id" in backend_op_names:
        for q_phys in meas_qubits:
            ro0.id(q_phys)
    ro0.barrier(*meas_qubits)
    for inst in meas_insts:
        ro0.append(inst.operation, inst.qubits, inst.clbits)

    for q_phys in meas_qubits:
        if "x" in backend_op_names:
            ro1.x(q_phys)
        else:
            ro1.sx(q_phys)
            ro1.sx(q_phys)
    ro1.barrier(*meas_qubits)
    for inst in meas_insts:
        ro1.append(inst.operation, inst.qubits, inst.clbits)

    return ro0, ro1


def extract_pub_counts(pub_res) -> dict:
    """Safely extract bitstring count dictionary from a SamplerV2 PUB result."""
    if hasattr(pub_res.data, "meas"):
        return pub_res.data.meas.get_counts()
    for val in pub_res.data.values():
        if hasattr(val, "get_counts"):
            return val.get_counts()
    return pub_res.join_data().get_counts()


def connect_ibm_service(token: str = None, channel: str = "ibm_quantum_platform", instance: str = None) -> QiskitRuntimeService:
    """Connect to QiskitRuntimeService using explicit token/CRN or saved local credentials."""
    kwargs = {"channel": channel}
    if token:
        kwargs["token"] = token
    if instance:
        kwargs["instance"] = instance
    return QiskitRuntimeService(**kwargs)


def decode_counts_payload(
    raw_counts_list: list,
    vqlds_cfg: dict,
    circuits_meta: dict,
    shots: int,
    backend_name: str = "ibm_hardware",
    job_id: str = ""
) -> None:
    """
    Decode raw bitstring counts from the 8-PUB hardware batch into physical Osimertinib
    PK trajectories (raw, readout-mitigated, and readout + 1x/3x ZNE) and 10/50/100-qubit
    HH-CD-QAOA metrics without any clamping to ideal or Radau values.
    """
    counts_ro0 = raw_counts_list[0]
    counts_ro1 = raw_counts_list[1]
    counts_8q_f1 = raw_counts_list[2]
    counts_8q_f3 = raw_counts_list[3]
    counts_10q_f1 = raw_counts_list[4]
    counts_10q_f3 = raw_counts_list[5]
    counts_50q = raw_counts_list[6]
    counts_100q = raw_counts_list[7]

    shots_ro0 = max(sum(counts_ro0.values()), 1)
    shots_ro1 = max(sum(counts_ro1.values()), 1)
    shots_f1 = max(sum(counts_8q_f1.values()), 1)
    shots_f3 = max(sum(counts_8q_f3.values()), 1)

    # 1. Empirical per-bit 2x2 readout assignment matrix measured on the exact 8 physical qubits
    eps_0_to_1 = np.zeros(8, dtype=float)
    eps_1_to_0 = np.zeros(8, dtype=float)
    for b, c in counts_ro0.items():
        bits = b.replace(" ", "")
        for pos in range(8):
            if bits[pos] == "1":
                eps_0_to_1[pos] += c / shots_ro0
    for b, c in counts_ro1.items():
        bits = b.replace(" ", "")
        for pos in range(8):
            if bits[pos] == "0":
                eps_1_to_0[pos] += c / shots_ro1

    inv_ro_full = np.array([[1.0]])
    for pos in range(8):
        e01 = min(max(eps_0_to_1[pos], 0.0), 0.45)
        e10 = min(max(eps_1_to_0[pos], 0.0), 0.45)
        r_mat = np.array([[1.0 - e01, e10], [e01, 1.0 - e10]], dtype=float)
        inv_ro_full = np.kron(inv_ro_full, np.linalg.inv(r_mat))

    p1 = np.zeros(256, dtype=float)
    p3 = np.zeros(256, dtype=float)
    for b, c in counts_8q_f1.items():
        p1[int(b.replace(" ", ""), 2)] = c / shots_f1
    for b, c in counts_8q_f3.items():
        p3[int(b.replace(" ", ""), 2)] = c / shots_f3

    p1_ro = np.maximum(inv_ro_full @ p1, 0.0)
    p1_ro /= max(float(np.sum(p1_ro)), 1e-12)

    p3_ro = np.maximum(inv_ro_full @ p3, 0.0)
    p3_ro /= max(float(np.sum(p3_ro)), 1e-12)

    p_zne = np.maximum(1.5 * p1_ro - 0.5 * p3_ro, 0.0)
    p_zne /= max(float(np.sum(p_zne)), 1e-12)

    # 2. Decode 72-h trajectories directly from hardware probabilities using VQLS scales
    t32 = np.linspace(0.0, 72.0, 32)
    alpha_star = float(vqlds_cfg.get("alpha_star", 1.0))
    scales = np.array(vqlds_cfg.get("scales", [1.0] * 8), dtype=float)
    perm = np.array(vqlds_cfg.get("perm_chrono_to_q", list(range(256))), dtype=int)
    d_right = np.tile(scales, 32)

    u_hw_raw = (alpha_star * np.sqrt(p1[perm]) * d_right).reshape(32, 8)
    u_hw_ro = (alpha_star * np.sqrt(p1_ro[perm]) * d_right).reshape(32, 8)
    u_hw_zne = (alpha_star * np.sqrt(p_zne[perm]) * d_right).reshape(32, 8)

    df_hw_traj = pd.DataFrame({
        "time_h": np.round(t32, 4),
        "C_osimertinib_uM_ibm_raw": np.round(u_hw_raw[:, 1], 6),
        "C_osimertinib_uM_ibm_ro": np.round(u_hw_ro[:, 1], 6),
        "C_osimertinib_uM_ibm_zne": np.round(u_hw_zne[:, 1], 6),
        "C_AZ5104_uM_ibm_raw": np.round(u_hw_raw[:, 2], 6),
        "C_AZ5104_uM_ibm_ro": np.round(u_hw_ro[:, 2], 6),
        "C_AZ5104_uM_ibm_zne": np.round(u_hw_zne[:, 2], 6),
        "C_AZ7550_uM_ibm_raw": np.round(u_hw_raw[:, 3], 6),
        "C_AZ7550_uM_ibm_ro": np.round(u_hw_ro[:, 3], 6),
        "C_AZ7550_uM_ibm_zne": np.round(u_hw_zne[:, 3], 6)
    })
    df_hw_traj.to_csv(RESULTS_DIR / "ibm_hardware_vqlds_trajectories.csv", index=False)

    # 3. Evaluate 10q (with 1x/3x ZNE), 50q, and 100q HH-CD-QAOA hardware schedules
    def eval_qaoa_counts(cnts: dict, n_q: int, h_vec: np.ndarray, j_weights: dict) -> tuple:
        tot_s = max(sum(cnts.values()), 1)
        mean_e = 0.0
        min_e = 1e9
        max_e = -1e9
        top_b = max(cnts, key=cnts.get)
        for bitstr, cnt in cnts.items():
            bits = bitstr.replace(" ", "")
            spins = np.array([1.0 if bits[n_q - 1 - q] == "0" else -1.0 for q in range(n_q)])
            e_val = float(np.dot(h_vec, spins))
            for (u, v), w_uv in j_weights.items():
                e_val += w_uv * spins[u] * spins[v]
            mean_e += (cnt / tot_s) * e_val
            min_e = min(min_e, e_val)
            max_e = max(max_e, e_val)
        return mean_e, min_e, max_e, top_b

    qaoa_hardware_metrics = {}

    # 10-qubit core polypharmacy (1x + 3x native CZ ZNE)
    h10, j10, jd10 = circuits_meta[10]
    e_min_10, e_max_10 = estimate_sparse_energy_bounds(h10, jd10, 10)
    mean10_1x, min10_1x, max10_1x, top10 = eval_qaoa_counts(counts_10q_f1, 10, h10, j10)
    mean10_3x, _, _, _ = eval_qaoa_counts(counts_10q_f3, 10, h10, j10)
    mean10_zne = 1.5 * mean10_1x - 0.5 * mean10_3x
    span10 = max(max(e_max_10, max10_1x) - min(e_min_10, min10_1x), 1e-12)
    worst10 = max(e_max_10, max10_1x)

    qaoa_hardware_metrics["10q"] = {
        "raw_mean_ising_energy": round(mean10_1x, 4),
        "fold3_mean_ising_energy": round(mean10_3x, 4),
        "zne_mean_ising_energy": round(mean10_zne, 4),
        "best_sampled_energy": round(min10_1x, 4),
        "raw_mean_ar": round(float((worst10 - mean10_1x) / span10), 4),
        "zne_mean_ar": round(float((worst10 - mean10_zne) / span10), 4),
        "best_sample_ar": round(float((worst10 - min10_1x) / span10), 4),
        "most_frequent_bitstring": top10,
        "unique_bitstrings_sampled": len(counts_10q_f1)
    }

    for n_q, cnts in [(50, counts_50q), (100, counts_100q)]:
        h_vec, j_weights, j_dense = circuits_meta[n_q]
        e_min_b, e_max_b = estimate_sparse_energy_bounds(h_vec, j_dense, n_q)
        mean_e, min_e, max_e, top_b = eval_qaoa_counts(cnts, n_q, h_vec, j_weights)
        best_e = min(e_min_b, min_e)
        worst_e = max(e_max_b, max_e)
        span = max(worst_e - best_e, 1e-12)
        qaoa_hardware_metrics[f"{n_q}q"] = {
            "raw_mean_ising_energy": round(mean_e, 4),
            "best_sampled_energy": round(min_e, 4),
            "raw_mean_ar": round(float((worst_e - mean_e) / span), 4),
            "best_sample_ar": round(float((worst_e - min_e) / span), 4),
            "most_frequent_bitstring": top_b,
            "unique_bitstrings_sampled": len(cnts)
        }

    vqlds_hw_summary = {
        "mean_8q_readout_error_0_to_1": round(float(np.mean(eps_0_to_1)), 5),
        "mean_8q_readout_error_1_to_0": round(float(np.mean(eps_1_to_0)), 5),
        "raw_Cmax_uM": round(float(np.max(u_hw_raw[:, 1])), 5),
        "ro_Cmax_uM": round(float(np.max(u_hw_ro[:, 1])), 5),
        "zne_Cmax_uM": round(float(np.max(u_hw_zne[:, 1])), 5),
        "raw_AUC_0_72h": round(float(np.trapezoid(u_hw_raw[:, 1], t32)), 4),
        "ro_AUC_0_72h": round(float(np.trapezoid(u_hw_ro[:, 1], t32)), 4),
        "zne_AUC_0_72h": round(float(np.trapezoid(u_hw_zne[:, 1], t32)), 4)
    }

    radau_csv = STIFF_RESULTS_DIR / "stiff_dynamics_trajectories.csv"
    if radau_csv.exists():
        df_rad = pd.read_csv(radau_csv)
        for label, col_rad, m_idx in [
            ("osimertinib", "C_osimertinib_uM_radau", 1),
            ("az5104", "C_AZ5104_uM_radau", 2),
            ("az7550", "C_AZ7550_uM_radau", 3),
        ]:
            y_ref = df_rad[col_rad].to_numpy(dtype=float)
            ss_tot = max(float(np.sum((y_ref - np.mean(y_ref)) ** 2)), 1e-12)
            r2_raw = 1.0 - float(np.sum((y_ref - u_hw_raw[:, m_idx]) ** 2)) / ss_tot
            r2_ro = 1.0 - float(np.sum((y_ref - u_hw_ro[:, m_idx]) ** 2)) / ss_tot
            r2_zne = 1.0 - float(np.sum((y_ref - u_hw_zne[:, m_idx]) ** 2)) / ss_tot
            vqlds_hw_summary[f"{label}_raw_r2_vs_radau"] = round(r2_raw, 4)
            vqlds_hw_summary[f"{label}_ro_r2_vs_radau"] = round(r2_ro, 4)
            vqlds_hw_summary[f"{label}_zne_r2_vs_radau"] = round(r2_zne, 4)

    out_payload = {
        "backend_name": backend_name,
        "job_id": job_id,
        "shots_per_circuit": shots,
        "vqlds_8q_hardware_osimertinib": vqlds_hw_summary,
        "vqlds_8q_top_basis_states_fold1": sorted(counts_8q_f1.items(), key=lambda kv: kv[1], reverse=True)[:8],
        "hh_cd_qaoa_hardware": qaoa_hardware_metrics
    }

    out_path = RESULTS_DIR / "ibm_real_hardware_results.json"
    with open(out_path, "w", encoding="utf-8") as handle:
        json.dump(out_payload, handle, indent=2)
    print(f"Saved decoded IBM hardware results to: {out_path}")


def archive_and_decode_pub_results(
    pub_results,
    vqlds_cfg: dict,
    circuits_meta: dict,
    shots: int,
    backend_name: str = "ibm_hardware",
    job_id: str = ""
) -> None:
    """Save untouched raw hardware bitstring counts immediately, then decode physical observables."""
    raw_counts_list = [extract_pub_counts(pub_results[idx]) for idx in range(len(pub_results))]
    raw_archive = {
        "backend_name": backend_name,
        "job_id": job_id,
        "shots_per_circuit": shots,
        "pub_names": [
            "vqlds_8q_ro0",
            "vqlds_8q_ro1",
            "vqlds_8q_fold1",
            "vqlds_8q_fold3",
            "hh_cd_qaoa_10q_fold1",
            "hh_cd_qaoa_10q_fold3",
            "hh_cd_qaoa_50q",
            "hh_cd_qaoa_100q"
        ],
        "counts": raw_counts_list
    }
    raw_path = RESULTS_DIR / "ibm_raw_hardware_counts.json"
    with open(raw_path, "w", encoding="utf-8") as handle:
        json.dump(raw_archive, handle, indent=2)
    print(f"Archived untouched raw hardware counts to: {raw_path}")

    decode_counts_payload(raw_counts_list, vqlds_cfg, circuits_meta, shots, backend_name, job_id)


def main() -> None:
    parser = argparse.ArgumentParser(description="Submit or fetch QClearance circuits on IBM Quantum hardware.")
    parser.add_argument("--token", type=str, default=os.environ.get("IBM_QUANTUM_TOKEN"), help="IBM Quantum API token")
    parser.add_argument("--channel", type=str, default="ibm_quantum_platform", choices=["ibm_quantum_platform", "ibm_cloud"])
    parser.add_argument("--instance", type=str, default=os.environ.get("IBM_QUANTUM_INSTANCE"), help="Optional CRN / instance")
    parser.add_argument("--backend", type=str, default=None, help="Specific backend (e.g. ibm_marrakesh, ibm_torino)")
    parser.add_argument("--shots", type=int, default=4096, help="Shots per circuit PUB (default: 4096)")
    parser.add_argument("--dry-run", action="store_true", help="Inspect circuit depths locally without submitting a cloud job")
    parser.add_argument("--wait", action="store_true", help="Wait synchronously for hardware queue completion")
    parser.add_argument("--fetch-job", type=str, default=None, help="Retrieve results from a previously submitted Job ID")
    parser.add_argument("--redecode-local", action="store_true", help="Re-decode from archived ibm_raw_hardware_counts.json")
    args = parser.parse_args()

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    vqlds_path = STIFF_RESULTS_DIR / "optimal_vqlds_8q_angles.json"
    qaoa_path = QAOA_RESULTS_DIR / "optimal_qaoa_params.json"
    if not vqlds_path.exists() or not qaoa_path.exists():
        raise FileNotFoundError(
            "Pre-converged parameter files not found in results/02_stiff_dynamics/ or results/03_polypharmacy_qaoa/. "
            "Run `python src/02_quantum_stiff_dynamics.py` and `python src/03_quantum_polypharmacy_qaoa.py` first."
        )

    with open(vqlds_path, "r", encoding="utf-8") as handle:
        vqlds_cfg = json.load(handle)
    with open(qaoa_path, "r", encoding="utf-8") as handle:
        qaoa_cfg = json.load(handle)
    df_poly = pd.read_csv(DATA_DIR / "master_polypharmacy_10drug_inputs.csv")

    qc_8q = build_8q_vqlds_circuit(vqlds_cfg["gates"], vqlds_cfg["n_qubits"], cx_fold=1)
    qc_10q, h10, j10, jd10 = build_nq_hh_cd_qaoa_circuit(10, df_poly, qaoa_cfg)
    qc_50q, h50, j50, jd50 = build_nq_hh_cd_qaoa_circuit(50, df_poly, qaoa_cfg)
    qc_100q, h100, j100, jd100 = build_nq_hh_cd_qaoa_circuit(100, df_poly, qaoa_cfg)

    circuits_meta = {10: (h10, j10, jd10), 50: (h50, j50, jd50), 100: (h100, j100, jd100)}

    if args.redecode_local:
        raw_path = RESULTS_DIR / "ibm_raw_hardware_counts.json"
        with open(raw_path, "r", encoding="utf-8") as handle:
            arch = json.load(handle)
        decode_counts_payload(
            arch["counts"], vqlds_cfg, circuits_meta,
            int(arch.get("shots_per_circuit", args.shots)),
            arch.get("backend_name", "ibm_hardware"),
            arch.get("job_id", "")
        )
        return

    if args.dry_run:
        print("Dry-run summary of base logical circuits before Heavy-Hex ISA transpilation & post-transpile 3x folding:")
        for qc in [qc_8q, qc_10q, qc_50q, qc_100q]:
            print(f"  - {qc.name:20s} | qubits={qc.num_qubits:3d} | depth={qc.depth():3d} | ops={dict(qc.count_ops())}")
        return

    service = connect_ibm_service(token=args.token, channel=args.channel, instance=args.instance)

    if args.fetch_job:
        print(f"Fetching job {args.fetch_job} from IBM Quantum...")
        job = service.job(args.fetch_job)
        status = str(job.status())
        print(f"Job status: {status}")
        if "DONE" in status.upper():
            b_name = getattr(job.backend(), "name", "ibm_hardware") if job.backend() else "ibm_hardware"
            archive_and_decode_pub_results(job.result(), vqlds_cfg, circuits_meta, args.shots, b_name, args.fetch_job)
        return

    if args.backend:
        backend = service.backend(args.backend)
    else:
        backend = service.least_busy(operational=True, simulator=False, min_num_qubits=100)
    print(f"Selected IBM Quantum processor: {backend.name} ({backend.num_qubits} physical qubits)")

    pm = generate_preset_pass_manager(optimization_level=3, backend=backend)
    isa_8q_f1 = pm.run(qc_8q)
    isa_8q_ro0, isa_8q_ro1 = build_isa_readout_cal_circuits(isa_8q_f1, set(backend.target.operation_names))
    isa_8q_f3 = fold_isa_2q_gates(isa_8q_f1, fold_factor=3, name="vqlds_8q_fold3")

    isa_10q_f1 = pm.run(qc_10q)
    isa_10q_f1.name = "hh_cd_qaoa_10q_fold1"
    isa_10q_f3 = fold_isa_2q_gates(isa_10q_f1, fold_factor=3, name="hh_cd_qaoa_10q_fold3")

    isa_50q = pm.run(qc_50q)
    isa_100q = pm.run(qc_100q)

    isa_circuits = [
        isa_8q_ro0,
        isa_8q_ro1,
        isa_8q_f1,
        isa_8q_f3,
        isa_10q_f1,
        isa_10q_f3,
        isa_50q,
        isa_100q
    ]

    # Validate every ISA circuit against backend.target locally before spending any QPU time
    validate_isa_circuits(isa_circuits, backend.target)

    transpile_stats = []
    for qc_isa in isa_circuits:
        ops = {str(k): int(v) for k, v in qc_isa.count_ops().items()}
        meas_phys = [
            int( qc_isa.find_bit(inst.qubits[0]).index )
            for inst in qc_isa.data if inst.operation.name == "measure"
        ]
        transpile_stats.append({
            "name": qc_isa.name,
            "measured_qubits": len(meas_phys),
            "physical_qubit_indices": meas_phys if len(meas_phys) <= 12 else f"{len(meas_phys)}_physical_qubits",
            "isa_depth": int(qc_isa.depth()),
            "gate_counts": ops
        })
        print(f"  ISA validated {qc_isa.name:22s} | depth = {qc_isa.depth():4d} | cz = {ops.get('cz', ops.get('ecr', 0)):4d}")

    sampler = SamplerV2(mode=backend)
    sampler.options.default_shots = args.shots
    sampler.options.dynamical_decoupling.enable = True
    sampler.options.dynamical_decoupling.sequence_type = "XX"
    sampler.options.dynamical_decoupling.skip_reset_qubits = True
    sampler.options.twirling.enable_gates = True
    sampler.options.twirling.enable_measure = True

    job = sampler.run(isa_circuits, shots=args.shots)
    job_id = job.job_id()
    print(f"\nSubmitted 8-PUB batch to {backend.name}. Job ID: {job_id}")

    manifest = {
        "backend_name": backend.name,
        "backend_num_qubits": int(backend.num_qubits),
        "job_id": job_id,
        "shots": args.shots,
        "error_suppression": [
            "XX_dynamical_decoupling_skip_reset",
            "pauli_gate_twirling",
            "measurement_twirling",
            "same_batch_8q_readout_calibration",
            "post_transpile_barrier_protected_1x_3x_2Q_ZNE"
        ],
        "transpiled_circuits": transpile_stats
    }
    with open(RESULTS_DIR / "ibm_job_manifest.json", "w", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=2)

    if args.wait:
        print("Waiting for IBM Quantum hardware queue completion (Ctrl+C safe: Job ID is saved in ibm_job_manifest.json)...")
        pub_res = job.result()
        archive_and_decode_pub_results(pub_res, vqlds_cfg, circuits_meta, args.shots, backend.name, job_id)
    else:
        print(f"Job queued! Re-run with `--fetch-job {job_id}` once completed on IBM Quantum Platform.")


if __name__ == "__main__":
    main()
